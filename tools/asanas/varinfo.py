 ('toes', R_(r'на носк|на кончиках пальцев'), 'вес на носках — сложнее баланс', 'hard'),
 ('nosupport', R_(r'без опоры'), 'без опоры — сложнее баланс и сила', 'hard'),
 ('bind', R_(r'связан|в замке|замок|захват|сцеплен|обвива'), 'захват или замок рук — сильнее раскрываются плечи', 'hard'),
