def tagset(ru): return [t for t,rx,_,_ in RULES if rx.search(ru)]
def describe(ru, base_ru, base_fam):
    own=set(tagset(base_ru))
    tags=[t for t in tagset(ru) if t not in own]
    what=[w for t,rx,w,_ in RULES if t in tags]
    roles={r for t,rx,_,r in RULES if t in tags}
    if 'hard' in roles: role='усложнение'
    elif 'easy' in roles: role='облегчение'
    elif 'prop' in roles: role='с опорой'
    else: role='другой акцент'
    if 'prop' in roles and role=='облегчение': role='облегчение с опорой'
    if not what: what=['небольшое изменение положения тела при той же основе позы']
    if role.startswith('облегчение') or role=='с опорой':
        rep=f'Да. Может заменить базовую асану («{base_ru}»), если она пока не получается, есть усталость, скованность или ограничения по здоровью.'
    elif role=='усложнение':
        rep=f'Нет. Это следующий шаг после базовой асаны («{base_ru}»): переходить к нему, когда базовая выполняется уверенно и без боли.'
    else:
        rep=f'Частично. Основа та же, что у «{base_ru}», но смещается акцент — можно чередовать с базовой для разнообразия.'
    extra=[EXTRA[t] for t in tags if t in EXTRA]
    if base_fam=='Лёжа на животе' or 'лёжа на животе' in ru.lower(): extra.append('беременность (лёжа на животе)')
    if re.search(r'присед|гирлянд|на пятках|ваджрасан|герой', ru, re.I): extra.append('чувствительные колени — плед под колени или сесть выше')
    return dict(tags=tags, what=what, role=role, replace=rep, extra=extra)
