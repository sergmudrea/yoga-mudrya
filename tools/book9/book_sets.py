    for i in mir:
        lines.append(f'        {kstr(i)},')
    lines.append('    )')
    lines.append('')
    lines.append('    fun set(id: String): BookSet? = sets.firstOrNull { it.id == id }')
    lines.append('}')
    open(out, 'w').write('\n'.join(lines) + '\n')
    return ids

