    lines.append('        )')
    lines.append('    }')
    lines.append('')
    lines.append('    val sequences: List<SequenceDef> by lazy { sets.map { SequenceDef(it.id, it.nameRu, it.nameEn, listOf(BlockRef(it.id))) } }')
